import { getCollection, type CollectionEntry } from 'astro:content';
import menuJson from '../data/menu.json';
import tagsJson from '../data/tags.json';

export type MenuItem = { title: string; url: string; children: MenuItem[] };
export type AnyEntry = CollectionEntry<'pages'> | CollectionEntry<'posts'> | CollectionEntry<'courses'>;

export const BASE = import.meta.env.BASE_URL.replace(/\/$/, '');
/** Prefix a root-absolute site path with the base path. */
export const href = (u: string) => (u.startsWith('/') && !u.startsWith('//') ? BASE + u : u);

export const TELEGRAM = 'https://t.me/+Xwfg03eSEd4yNDYy';

/** Main menu without «Главная»; «Описание комплекта» children kept (they point at the grade page). */
export const menu: MenuItem[] = (menuJson as MenuItem[]).filter((m) => m.url !== '/');

export function menuTrail(url: string, items: MenuItem[] = menu, trail: MenuItem[] = []): MenuItem[] | null {
  for (const it of items) {
    const here = [...trail, it];
    const deeper = menuTrail(url, it.children, here);
    if (deeper) return deeper;
    if (it.url === url) return here;
  }
  return null;
}

/** The grade (top-level menu item) a URL belongs to, if any. */
export const gradeOf = (url: string) => menuTrail(url)?.[0] ?? null;

let cache: AnyEntry[] | null = null;
export async function allEntries(): Promise<AnyEntry[]> {
  if (!cache) {
    const all = [
      ...(await getCollection('pages')),
      ...(await getCollection('posts')),
      ...(await getCollection('courses')),
    ] as AnyEntry[];
    cache = all.filter((e) => !e.data.draft);
  }
  return cache;
}

// ------------------------------------------------------------------ courses

export type CourseNode = {
  entry: CollectionEntry<'courses'>;
  url: string;
  title: string;
  children: CourseNode[];
};

const depth = (url: string) => url.split('/').filter(Boolean).length;
const ord = (e: CollectionEntry<'courses'>) => e.data.order ?? 0;

export async function courseTree(courseSlug: string): Promise<CourseNode | null> {
  const entries = (await allEntries()).filter(
    (e) => e.collection === 'courses' && e.data.url.startsWith(`/${courseSlug}/`),
  ) as CollectionEntry<'courses'>[];
  const root = entries.find((e) => depth(e.data.url) === 1);
  if (!root) return null;
  const node = (e: CollectionEntry<'courses'>): CourseNode => ({
    entry: e,
    url: e.data.url,
    title: e.data.title,
    children: entries
      .filter((c) => depth(c.data.url) === depth(e.data.url) + 1 && c.data.url.startsWith(e.data.url))
      .sort((a, b) => ord(a) - ord(b))
      .map(node),
  });
  return node(root);
}

/** Pages of a course in reading order (sections, their items, book chapters). */
export function flatten(n: CourseNode): CourseNode[] {
  return [n, ...n.children.flatMap(flatten)];
}

/** Section titles in Moodle often repeat the course name; keep them short in navigation. */
export function shortTitle(t: string) {
  return t.replace(/^Т\.С\. Троицкая\. /, '').replace(/^Учебное пособие «Такие непохожие писатели»: введение$/, 'Учебное пособие: введение');
}

// Moodle tags (generated by the converter): slug -> name and items grouped as on Moodle's tag pages
export type TagItem = { title: string; url: string; course: string; section?: string; context?: string };
export type Tag = { name: string; groups: { title: string; items: TagItem[] }[] };
export const tags = tagsJson as Record<string, Tag>;
const slugByName = new Map(Object.entries(tags).map(([slug, t]) => [t.name, slug]));
export function tagSlug(name: string): string {
  const s = slugByName.get(name);
  if (!s) throw new Error(`unknown tag ${name}`);
  return s;
}
export const tagCount = (t: Tag) => t.groups.reduce((n, g) => n + g.items.length, 0);
